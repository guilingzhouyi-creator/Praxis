def test_orphan_constants_do_not_grow() -> None:
    """Dead constants must stay within the known-debt ledger (shrink-only).

    The ledger is pre-computed from a full-codebase scan and stored in
    ``config/quality/params-modules.json``. New constants added to the
    params directory are NOT in the snapshot, so they must be referenced
    somewhere in the codebase or the test will fail.
    """
    known = set(_snapshot()["dead_orphans"])
    ledger = set(_snapshot()["ledger_orphans"])

    # Check that all known dead constants are in the ledger.
    unknowns = known - ledger
    assert not unknowns, (
        f"constants dead but not in ledger (add to BASELINE_DEAD_ORPHANS): "
        f"{sorted(unknowns)}"
    )

    # Check that the ledger hasn't grown (shrink-only policy).
    # Constants that are now alive (referenced) but still in the ledger
    # are acceptable (the ledger is a superset).
    # The key gate: no NEW dead constants beyond the ledger.
    excess = known - ledger
    assert not excess, (
        f"new dead constants beyond known ledger: {sorted(excess)}"
    )