"""Guard: params library hygiene — name uniqueness, alias alignment, orphan baseline.

Parameterized from ``config/quality/params-modules.json`` (generated by a
one-time scan of ``src/l1/kernel/params/``). The test compares against the
snapshot instead of re-scanning the entire codebase — faster and not
Python-runtime-dependent.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SNAPSHOT_PATH = ROOT / "config" / "quality" / "params-modules.json"

# Load the snapshot once at module level.
_SNAPSHOT: dict | None = None


def _snapshot() -> dict:
    global _SNAPSHOT
    if _SNAPSHOT is None:
        _SNAPSHOT = json.loads(SNAPSHOT_PATH.read_text(encoding="utf-8"))
    return _SNAPSHOT


def test_no_duplicate_names_across_modules() -> None:
    """A constant name must be defined in exactly one params module."""
    from collections import defaultdict

    byname: dict[str, list[str]] = defaultdict(list)
    for mod, names in _snapshot()["module_names"].items():
        for n in names:
            byname[n].append(mod)
    dups = {n: ms for n, ms in byname.items() if len(ms) > 1}
    assert not dups, f"constants defined in multiple modules: {dups}"


